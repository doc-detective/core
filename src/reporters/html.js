const fs = require("fs");
const path = require("path");
const { log } = require("../utils");

exports.generateHtmlReport = generateHtmlReport;

/**
 * Generates a self-contained HTML report from test results
 * @param {Object} results - The test results object from runTests
 * @param {Object} config - The configuration object
 * @param {string} outputPath - Path where the HTML report should be saved
 * @returns {Object} Status object with result and path
 */
async function generateHtmlReport(results, config, outputPath) {
  try {
    const html = buildHtmlReport(results);
    
    // Ensure directory exists
    const dir = path.dirname(outputPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    
    fs.writeFileSync(outputPath, html, 'utf8');
    log(config, "info", `HTML report generated at ${outputPath}`);
    
    return {
      status: "PASS",
      description: "HTML report generated successfully",
      path: outputPath
    };
  } catch (error) {
    log(config, "error", `Failed to generate HTML report: ${error.message}`);
    return {
      status: "FAIL",
      description: `Failed to generate HTML report: ${error.message}`
    };
  }
}

/**
 * Builds the complete HTML report with embedded CSS
 * @param {Object} results - The test results object
 * @returns {string} Complete HTML document
 */
function buildHtmlReport(results) {
  const timestamp = new Date().toISOString();
  const summary = results.summary || {};
  
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Doc Detective Test Results</title>
  <style>
    ${getEmbeddedCss()}
  </style>
</head>
<body>
  <div class="container">
    <header class="header">
      <h1>Doc Detective Test Results</h1>
      <div class="timestamp">Generated: ${formatTimestamp(timestamp)}</div>
    </header>
    
    ${buildSummarySection(summary)}
    ${buildSpecsSection(results.specs || [])}
    
    <footer class="footer">
      <p>Generated by <a href="https://doc-detective.com" target="_blank">Doc Detective</a></p>
    </footer>
  </div>
  
  <script>
    ${getEmbeddedScript()}
  </script>
</body>
</html>`;
}


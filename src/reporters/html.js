/**
 * Returns embedded JavaScript for interactive features
 * @returns {string} JavaScript code
 */
function getEmbeddedScript() {
  return `
    function toggleSection(element) {
      element.classList.toggle('expanded');
    }
    
    // Add click handlers to all expandable sections
    document.addEventListener('DOMContentLoaded', function() {
      // Expand first spec by default
      const firstSpec = document.querySelector('.spec');
      if (firstSpec) {
        firstSpec.classList.add('expanded');
      }
      
      // Add click handlers
      document.querySelectorAll('.spec-header').forEach(header => {
        header.addEventListener('click', function() {
          toggleSection(this.parentElement);
        });
      });
      
      document.querySelectorAll('.test-header').forEach(header => {
        header.addEventListener('click', function() {
          toggleSection(this.parentElement);
        });
      });
      
      document.querySelectorAll('.context-header').forEach(header => {
        header.addEventListener('click', function() {
          toggleSection(this.parentElement);
        });
      });
    });
  `;
}

/**
 * Formats a timestamp for display
 * @param {string} timestamp - ISO timestamp
 * @returns {string} Formatted timestamp
 */
function formatTimestamp(timestamp) {
  const date = new Date(timestamp);
  return date.toLocaleString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit'
  });
}

/**
 * Builds the summary section HTML
 * @param {Object} summary - Summary object from results
 * @returns {string} HTML string
 */
function buildSummarySection(summary) {
  const sections = ['specs', 'tests', 'contexts', 'steps'];
  
  return `
    <section class="summary">
      <h2>Test Summary</h2>
      <div class="summary-grid">
        ${sections.map(section => {
          const data = summary[section] || { pass: 0, fail: 0, warning: 0, skipped: 0 };
          const total = (data.pass || 0) + (data.fail || 0) + (data.warning || 0) + (data.skipped || 0);
          return `
            <div class="summary-card">
              <h3>${section}</h3>
              ${buildStatRow('Pass', data.pass || 0, 'pass')}
              ${buildStatRow('Fail', data.fail || 0, 'fail')}
              ${buildStatRow('Warning', data.warning || 0, 'warning')}
              ${buildStatRow('Skipped', data.skipped || 0, 'skipped')}
              <div class="stat-row" style="margin-top: 10px; font-weight: bold;">
                <span class="stat-label">Total</span>
                <span class="stat-value">${total}</span>
              </div>
            </div>
          `;
        }).join('')}
      </div>
    </section>
  `;
}

/**
 * Builds a stat row for the summary section
 * @param {string} label - Label for the stat
 * @param {number} value - Value of the stat
 * @param {string} type - Type (pass, fail, warning, skipped)
 * @returns {string} HTML string
 */
function buildStatRow(label, value, type) {
  return `
    <div class="stat-row">
      <span class="stat-label">${label}</span>
      <span class="stat-value badge badge-${type}">${value}</span>
    </div>
  `;
}

/**
 * Builds the specs section HTML
 * @param {Array} specs - Array of spec objects
 * @returns {string} HTML string
 */
function buildSpecsSection(specs) {
  if (!specs || specs.length === 0) {
    return `
      <section class="specs-section">
        <h2>Test Specifications</h2>
        <p>No test specifications found.</p>
      </section>
    `;
  }
  
  return `
    <section class="specs-section">
      <h2>Test Specifications</h2>
      ${specs.map(spec => buildSpec(spec)).join('')}
    </section>
  `;
}

/**
 * Builds HTML for a single spec
 * @param {Object} spec - Spec object
 * @returns {string} HTML string
 */
function buildSpec(spec) {
  const result = spec.result || 'SKIPPED';
  const badge = `<span class="badge badge-${result.toLowerCase()}">${result}</span>`;
  
  return `
    <div class="spec">
      <div class="spec-header">
        <div class="spec-title">
          <span class="expand-icon">▶</span>
          <h3>${escapeHtml(spec.description || spec.specId)}</h3>
        </div>
        ${badge}
      </div>
      <div class="spec-content">
        <div class="spec-info">
          <strong>Spec ID:</strong> ${escapeHtml(spec.specId)}<br>
          ${spec.contentPath ? `<strong>Path:</strong> ${escapeHtml(spec.contentPath)}<br>` : ''}
        </div>
        ${buildTests(spec.tests || [])}
      </div>
    </div>
  `;
}

/**
 * Builds HTML for tests
 * @param {Array} tests - Array of test objects
 * @returns {string} HTML string
 */
function buildTests(tests) {
  if (!tests || tests.length === 0) {
    return '<p>No tests found in this specification.</p>';
  }
  
  return tests.map(test => buildTest(test)).join('');
}

/**
 * Builds HTML for a single test
 * @param {Object} test - Test object
 * @returns {string} HTML string
 */
function buildTest(test) {
  const result = test.result || 'SKIPPED';
  const badge = `<span class="badge badge-${result.toLowerCase()}">${result}</span>`;
  
  return `
    <div class="test">
      <div class="test-header">
        <div class="test-title">
          <span class="expand-icon">▶</span>
          <h4>${escapeHtml(test.description || test.testId)}</h4>
        </div>
        ${badge}
      </div>
      <div class="test-content">
        <div class="test-info">
          <strong>Test ID:</strong> ${escapeHtml(test.testId)}<br>
          ${test.contentPath ? `<strong>Path:</strong> ${escapeHtml(test.contentPath)}<br>` : ''}
          ${test.detectSteps !== undefined ? `<strong>Detect Steps:</strong> ${test.detectSteps}<br>` : ''}
        </div>
        ${buildContexts(test.contexts || [])}
      </div>
    </div>
  `;
}

/**
 * Builds HTML for contexts
 * @param {Array} contexts - Array of context objects
 * @returns {string} HTML string
 */
function buildContexts(contexts) {
  if (!contexts || contexts.length === 0) {
    return '<p>No contexts found in this test.</p>';
  }
  
  return contexts.map(context => buildContext(context)).join('');
}

/**
 * Builds HTML for a single context
 * @param {Object} context - Context object
 * @returns {string} HTML string
 */
function buildContext(context) {
  const result = context.result || 'SKIPPED';
  const badge = `<span class="badge badge-${result.toLowerCase()}">${result}</span>`;
  const platform = context.platform ? escapeHtml(context.platform) : 'N/A';
  const browser = context.browser ? escapeHtml(context.browser) : 'N/A';
  
  return `
    <div class="context">
      <div class="context-header">
        <div class="context-title">
          <span class="expand-icon">▶</span>
          <span>Platform: ${platform} | Browser: ${browser}</span>
        </div>
        ${badge}
      </div>
      <div class="context-content">
        ${buildSteps(context.steps || [])}
      </div>
    </div>
  `;
}

/**
 * Builds HTML for steps
 * @param {Array} steps - Array of step objects
 * @returns {string} HTML string
 */
function buildSteps(steps) {
  if (!steps || steps.length === 0) {
    return '<p>No steps found in this context.</p>';
  }
  
  return `
    <div class="steps">
      ${steps.map((step, index) => buildStep(step, index)).join('')}
    </div>
  `;
}

/**
 * Builds HTML for a single step
 * @param {Object} step - Step object
 * @param {number} index - Step index
 * @returns {string} HTML string
 */
function buildStep(step, index) {
  const result = step.result || 'SKIPPED';
  const badge = `<span class="badge badge-${result.toLowerCase()}">${result}</span>`;
  
  // Determine the action type
  let action = 'Unknown';
  const stepKeys = Object.keys(step).filter(key => !['result', 'description', 'outputs'].includes(key));
  if (stepKeys.length > 0) {
    action = stepKeys[0];
  }
  
  return `
    <div class="step step-${result.toLowerCase()}">
      <div class="step-header">
        <span class="step-action">Step ${index + 1}: ${escapeHtml(action)}</span>
        ${badge}
      </div>
      ${step.description ? `<div class="step-description">${escapeHtml(step.description)}</div>` : ''}
      ${step.outputs ? `<div class="step-details">${escapeHtml(JSON.stringify(step.outputs, null, 2))}</div>` : ''}
    </div>
  `;
}

/**
 * Escapes HTML special characters
 * @param {string} text - Text to escape
 * @returns {string} Escaped text
 */
function escapeHtml(text) {
  if (typeof text !== 'string') {
    return String(text);
  }
  const map = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;'
  };
  return text.replace(/[&<>"']/g, m => map[m]);
}
